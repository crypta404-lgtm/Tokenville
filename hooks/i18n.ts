const LANGS = { en, pt, es } as const
export type Lang = keyof typeof LANGS

let current: Lang = 'en'
/** Converte um locale do sistema (pt-BR, es_ES.UTF-8, en-US…) para um idioma suportado. */
export function pickLang(locale: string | undefined): Lang {
  const code = String(locale || '').toLowerCase().slice(0, 2)
  return code in LANGS ? (code as Lang) : 'en'
}
export function setLang(l: Lang): void {
  current = l
}
export function getLang(): Lang {
  return current
}
export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (LANGS[current] as Partial<Record<Key, string>>)[key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}
